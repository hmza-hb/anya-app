/// All face states from the Anya expression sheet.
enum AnyaExpression {
  idle,
  happy,
  sad,
  excited,
  curious,
  thinking,
  sleepy,
  surprised,
  winking,
  angry,
  inLove,
  accepted,
  speaking,
  listening,
  shy,
  proud,
  lookUp,
  lookDown,
  lookLeft,
  lookRight,
  thinkingHard,
  confused,
  listeningActive,
  speakingActive,
  processing,
  connecting,
  error,
  charging,
  lowBattery,
}

extension AnyaExpressionLabel on AnyaExpression {
  String get label => switch (this) {
        AnyaExpression.idle => 'Idle',
        AnyaExpression.happy => 'Happy',
        AnyaExpression.sad => 'Sad',
        AnyaExpression.excited => 'Excited',
        AnyaExpression.curious => 'Curious',
        AnyaExpression.thinking => 'Thinking',
        AnyaExpression.sleepy => 'Sleepy',
        AnyaExpression.surprised => 'Surprised',
        AnyaExpression.winking => 'Winking',
        AnyaExpression.angry => 'Angry',
        AnyaExpression.inLove => 'In Love',
        AnyaExpression.accepted => 'Accepted',
        AnyaExpression.speaking => 'Speaking',
        AnyaExpression.listening => 'Listening',
        AnyaExpression.shy => 'Shy',
        AnyaExpression.proud => 'Proud',
        AnyaExpression.lookUp => 'Look Up',
        AnyaExpression.lookDown => 'Look Down',
        AnyaExpression.lookLeft => 'Look Left',
        AnyaExpression.lookRight => 'Look Right',
        AnyaExpression.thinkingHard => 'Thinking Hard',
        AnyaExpression.confused => 'Confused',
        AnyaExpression.listeningActive => 'Listening',
        AnyaExpression.speakingActive => 'Speaking',
        AnyaExpression.processing => 'Processing',
        AnyaExpression.connecting => 'Connecting',
        AnyaExpression.error => 'Error',
        AnyaExpression.charging => 'Charging',
        AnyaExpression.lowBattery => 'Low Battery',
      };
}